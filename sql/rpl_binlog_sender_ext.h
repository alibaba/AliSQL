/**
  This class provide a writer to write a event to buffer.
*/
class Buffer_ostream : public virtual Basic_ostream {
 public:
  Buffer_ostream(uchar *buf_ptr, my_off_t buf_len)
      : position(0), m_buf_len(buf_len), m_buf(buf_ptr) {}

  bool write(const unsigned char *buffer, my_off_t length) override {
    if (position + length > m_buf_len) return true;

    memcpy(m_buf + position, buffer, length);
    position += length;

    return false;
  }

  my_off_t position;
  my_off_t m_buf_len;
  uchar *m_buf;
};

class Brr_binlog_sender {
  friend class Binlog_sender;

 public:
  Brr_binlog_sender(THD *thd, Binlog_sender *sender);
  ~Brr_binlog_sender();
  uint32 get_replica_server_id() { return m_thd->server_id; }
  my_thread_id get_dump_thread_id() { return m_thd->thread_id(); }

  /**
    This class provide a reader to read brr events from binlog cache, and save
    the buffer to packet. Each brr_trx has a brr_reader in each dump thread.
  */
  class Brr_reader;

  /**
    Send brr events to slave.

    It will traverse the brr reader list, found the readable reader by comparing
    position, read and sent one event for each readable reader.

    This function will be called by binlog dump thread. When finish sending
    normal events, dump thread will call this function and send one event for
    every brr_trx.

    @return false if success.
  */
  bool send_brr_events();

  /**
    Send FORMAT_DESCRIPTION_EVENT to slave. This event is the first event sent
    by brr, to help slave decode other brr events.

    @return false if success.
  */
  bool send_brr_fde_event();

  /**
    Update the brr reader list.

    @param have_lock Whether this function is called inside binlog_end_pos lock.
    @return true if updated brr reader list.
  */
  bool update_brr_reader_list(bool have_lock);

  /**
    Check whether the end_position or status has been updated.
    @param brr_ddl_wait_time Records the shortest waiting time for sending brr
    DDL.

    @return true if updated.
  */
  bool check_brr_reader_readable(
      std::chrono::nanoseconds *brr_ddl_wait_time = nullptr);

  /**
    This function will be called when dump thread read the gtid event from
    binlog. It will decode the gtid event, find brr reader with sid and gno, and
    send following events to slave if brr reader has been found.

    - If this transaction should be skipped for this slave(in_exclude_group =
    true), send a rollback brr message event to slave.
    - If in_exclude_group = false, send the rest brr event of this transaction
    to slave, send the gtid event to slave and send a heartbeat event to slave.
    The heartbeat event will correct the binlog position on slave, and will ask
    a ack if semi-sync is enabled.

    @param gtid_event_ptr The gtid event ptr of current transaction.
    @param checksum_alg The checksum algorithm of current binlog file.
    @param trx_start_pos The start pos of current transaction in binlog file.
    @param in_exclude_group Whether current transaction is exclude.
    @param[out] trx_end_pos The end position of this transaction in binlog, 0 if
    not found brr reader or in_exclude_group is true.
    @return false if everything goes well, true if unexpect error happened.
  */
  bool find_and_finish_brr_transaction(
      const uchar *gtid_event_ptr,
      binary_log::enum_binlog_checksum_alg checksum_alg, my_off_t trx_start_pos,
      bool in_exclude_group, my_off_t *trx_end_pos);

  bool is_reader_list_empty() const { return m_brr_reader_list.empty(); }

  /** Get the brr reader list. */
  std::list<Brr_reader *> *get_brr_reader_list() { return &m_brr_reader_list; }

  /**
    Send gtid_executed_log_event to slave. This event is used by the replica
    to confirm the timing of replaying a group of events.

    @param brr_reader The Brr_reader object ptr.
    @return false if success.
  */
  bool send_brr_gtid_executed_event(Brr_reader *brr_reader);

  /**
    Check if any brr event has been sent.

    @param brr_reader The Brr_reader object ptr.
    @return true if has sent some brr events.
  */
  bool check_has_sent_brr_events(Brr_reader *brr_reader);

 private:
  /**
    Remove the brr reader.

    @param brr_reader The Brr_reader object ptr.
    @param is_complete Whether this brr trx has complete sending all events.
  */
  void remove_reader(Brr_reader *brr_reader, bool is_complete);

  /**
    Send a brr rollback event to slave and remove the brr_reader.

    @param brr_reader The Brr_reader object ptr.
    @return false if success.
  */
  bool rollback_brr_transaction(Brr_reader *brr_reader);

  /**
    Send the brr gtid event to slave.

    @param brr_reader The Brr_reader object ptr.
    @param gtid_ev The last processed event type.
    @return false if success.
  */
  bool send_brr_gtid_event(Brr_reader *brr_reader, Gtid_log_event *gtid_ev);

  /**
    Reset the send packet for brr event. Brr header will be init in this
    function include brr magic code(2 byte) and brr_index(8 byte).

    @param event_len The length of event need fill in packet.
    @param brr_index The brr_index of event.
    @param magic_type The brr event header magic type.
    @return false if success.
  */
  bool brr_reset_packet(size_t event_len, ulonglong brr_index,
                        Brr_magic_type magic_type);

  THD *m_thd;
  Format_description_log_event m_fde;
  std::list<Brr_reader *> m_brr_reader_list;

  /** The max value of brr index in brr trx list. */
  ulonglong m_max_index = 0;
  Binlog_sender *m_sender;
};

