/** Brr_reader and Brr_binlog_sender information recorded in the IS table. */
struct Brr_sender_trx_info_t {
  /** The thread id of dump thread to send the brr_trx. */
  my_thread_id dump_thread_id;

  /** The server id of replica that dump thread send brr_trx to. */
  uint32 replica_server_id;

  /** The index of brr_trx. */
  uint64_t brr_idx;

  /** The position where this brr_trx has been sent. */
  uint64_t send_pos;

  /* The number of normal events sent to slave. */
  uint64_t trx_content_events_send;

  /* The number of brr events sent to slave. */
  uint64_t events_send;
};

/** Brr_trx information recorded in the IS table. */
struct Brr_source_trx_info_t {
  /** The thread id of the THD witch produce brr_trx. */
  my_thread_id brr_thread_id;

  /** The index of brr_trx. */
  uint64_t index;

  /** The type of brr_trx. */
  char type[BRR_TYPE_LEN];

  /** The status of brr_trx. */
  Brr_trx_status status;

  /** Start read pos of binlog cache tmp file of this brr_trx. */
  uint64_t start_read_pos;

  /** End_position is the latest readable position of this brr_trx. */
  uint64_t end_position;

  /** The name of binlog cache tmp file of this brr_trx. */
  char file_name[FN_REFLEN];

  /** Record the Gtid of this transaction. */
  rpl_gno gno;
};

class Brr_trx_manager {
 public:
  Brr_trx_manager();

  /* Initialize the pthread objects. */
  void init_pthread_objects();

  /**
    Create brr trx for a transaction, and append the brr trx to brr trx list.

    @param file_name The name of binlog cache tmp file of this transaction.
    @param end_pos The end_position of binlog cache tmp file.
    @param offset The offset of first event in binlog cache tmp file.
    @param buffer The buffer for DDL.
    @return The ptr of brr_trx of this transaction.
  */
  Brr_trx *open_brr_trx(const char *file_name, my_off_t end_pos,
                        my_off_t offset, uchar *buffer);

  /**
    Update gtid of brr trx.

    This function is called after gtid generated in the commit process, which
    means this transaction has finished writing all events to binlog cache tmp
    file, and will be committed later. Thus, the status of this transaction
    will be changed to finished.

    @param brr_trx The ptr of this brr trx, it should not be nullptr.
    @param sid_ptr The ptr of sid of this transaction.
    @param gno The gno of this transaction.
  */
  void update_brr_trx_gtid(Brr_trx *brr_trx, const rpl_sid *sid_ptr,
                           rpl_gno gno);

  /**
    Update status of brr trx.

    @param brr_trx The ptr of this brr trx, it should not be nullptr.
    @param status The status of this transaction.
  */
  void close_brr_trx(Brr_trx *brr_trx, Brr_trx_status status);

  /**
    Update end_position of brr trx.

    @param brr_trx The ptr of this brr trx, it should not be nullptr.
    @param end_position The end_position of this transaction.
  */
  void update_brr_trx_position(Brr_trx *brr_trx, my_off_t end_position) {
    assert(brr_trx != nullptr && end_position != 0);

    mysql_bin_log.lock_binlog_end_pos();
    assert(m_brr_trx_list[brr_trx->index] == brr_trx);

    if (end_position > brr_trx->end_position) {
      brr_trx->end_position.store(end_position);
      mysql_bin_log.signal_update();
    }

    mysql_bin_log.unlock_binlog_end_pos();
  }

  /**
    Try to delete the brr trx and remove it form brr trx list.

    @param brr_trx The brr trx object ptr, it should not be nullptr.
    @return True if the brr trx has been removed, otherwise false.
  */
  bool try_remove_trx(Brr_trx *brr_trx);

  std::unordered_map<ulonglong, Brr_trx *> *get_brr_trx_list() {
    return &m_brr_trx_list;
  }

  ulonglong get_max_index() { return m_max_index; }

  const ulonglong &get_limit_size_var() { return m_limit_size; }

  const ulonglong &get_read_block_size() { return m_cache_read_block_size; }

  const ulonglong &get_max_send_size() { return m_brr_max_send_size; }

  const bool &get_enabled() { return m_enabled; }

 private:
  /** The max value of brr index in brr trx list. */
  std::atomic<ulonglong> m_max_index;

  /** The brr trx list. Key: brr_index. Value: brr_trx. */
  std::unordered_map<ulonglong, Brr_trx *> m_brr_trx_list;

  /**
    The value of binlog_realtime_transmit_long_transaction_limit_size
    variable. We will check binlog cahce size with it after writing event to
    binlog cache, to determine whether a trx is a large trx.
  */
  ulonglong m_limit_size;

  /**
    The value of binlog_realtime_transmit_read_block_size variable. Every time
    when the new event write into binlog cahce exceeds the
    binlog_realtime_transmit_read_block_size, we flush binlog cache size and
    send them to replica relatimely.

    The default value of this variable is 2MB, it can avoid flush binlog cache
    too frequency.
  */
  ulonglong m_cache_read_block_size;

  /**
    The value of binlog_realtime_transmit_max_send_size variable. In order to
    avoid brr event obstruct the normal event, we restrict the max send size of
    brr event each round.

    - If single event of a transaction is larger than max_send_size, we do not
    send events of this transaction realtime, the events of this transaction
    will be sent after transaction commit, in find_and_finish_brr_transaction().

    - If the sum of events of one loop is larger than max_send_size, we will
    ignore the rest of transactions in this loop, and send them in next loop.
  */
  ulonglong m_brr_max_send_size;

  /**
    The value of Binlog_realtime_transmit_source_enabled variable.
  */
  bool m_enabled;
};

